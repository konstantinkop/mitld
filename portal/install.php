error_reporting(E_ALL);
ini_set('display_errors', '1');
date_default_timezone_set('UTC');

require_once __DIR__ . '/antibot.php';

$configFile = __DIR__ . '/config/config.php';
$config = file_exists($configFile) ? require $configFile : [];

$message = null;
$error = null;
$installed = false;

// Handle form submission
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $action = $_POST['action'] ?? '';

    if ($action === 'install') {
        $host = trim($_POST['host'] ?? 'localhost');
        $port = (int)($_POST['port'] ?? 3306);
        $dbname = trim($_POST['database'] ?? 'mitid');
        $user = trim($_POST['username'] ?? 'root');
        $pass = $_POST['password'] ?? '';
        $adminEmail = trim($_POST['admin_email'] ?? 'admin@miitid.com');
        $adminPass = $_POST['admin_password'] ?? 'Miitid@Admin2026!';

        try {
            // Test MySQL connection with automatic 127.0.0.1 fallback for localhost
            $connectHost = $host;
            try {
                $dsn = "mysql:host={$connectHost};port={$port};dbname={$dbname};charset=utf8mb4";
                $pdo = new PDO($dsn, $user, $pass, [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                ]);
            } catch (PDOException $pe) {
                if ($connectHost === 'localhost') {
                    $connectHost = '127.0.0.1';
                    $dsn = "mysql:host={$connectHost};port={$port};dbname={$dbname};charset=utf8mb4";
                    $pdo = new PDO($dsn, $user, $pass, [
                        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                    ]);
                    $host = '127.0.0.1';
                } else {
                    throw $pe;
                }
            }
            $pdo->exec("SET time_zone = '+00:00';");

            // Execute database.sql
            $sqlFile = __DIR__ . '/database.sql';
            if (file_exists($sqlFile)) {
                $sql = file_get_contents($sqlFile);
                $pdo->exec($sql);
            }

            // Update or ensure admin user with given password
            $hash = password_hash($adminPass, PASSWORD_BCRYPT);
            $stmt = $pdo->prepare("SELECT id FROM admins WHERE email = ?");
            $stmt->execute([$adminEmail]);
            if ($row = $stmt->fetch()) {
                $upd = $pdo->prepare("UPDATE admins SET password_hash = ? WHERE email = ?");
                $upd->execute([$hash, $adminEmail]);
            } else {
                $ins = $pdo->prepare("INSERT INTO admins (email, password_hash) VALUES (?, ?)");
                $ins->execute([$adminEmail, $hash]);
            }

            // Update config.php
            $newConfigContent = "<?php\n" .
                "/**\n * MitID Configuration File\n * Generated by install.php on " . date('Y-m-d H:i:s') . "\n */\n\n" .
                "return [\n" .
                "    'db' => [\n" .
                "        'driver' => 'mysql',\n" .
                "        'host' => " . var_export($host, true) . ",\n" .
                "        'port' => " . $port . ",\n" .
                "        'database' => " . var_export($dbname, true) . ",\n" .
                "        'username' => " . var_export($user, true) . ",\n" .
                "        'password' => " . var_export($pass, true) . ",\n" .
                "        'charset' => 'utf8mb4',\n" .
                "        'auto_sqlite_fallback' => true,\n" .
                "        'sqlite_path' => __DIR__ . '/../data/mitid.sqlite',\n" .
                "    ],\n" .
                "    'jwt' => [\n" .
                "        'secret' => " . var_export(bin2hex(random_bytes(24)), true) . ",\n" .
                "        'expiry' => 86400,\n" .
                "    ],\n" .
                "    'admin' => [\n" .
                "        'default_email' => " . var_export($adminEmail, true) . ",\n" .
                "        'default_password' => " . var_export($adminPass, true) . ",\n" .
                "    ],\n" .
                "    'app' => [\n" .
                "        'name' => 'MitID Portal',\n" .
                "        'debug' => false,\n" .
                "    ],\n" .
                "];\n";

            @file_put_contents($configFile, $newConfigContent);
            @file_put_contents(__DIR__ . '/config/installed.php', $newConfigContent);

            $message = "Installation completed successfully! Tables created and admin account configured.";
            $installed = true;
        } catch (Exception $e) {
            $msg = $e->getMessage();
            $hint = '';
            if (strpos($msg, '2002') !== false) {
                $hint = "<div style='margin-top:10px; padding:10px; background:rgba(0,0,0,0.04); border-radius:6px; font-size:13px; line-height:1.5;'>" .
                        "<strong>🌐 If hosting on InfinityFree:</strong><br>" .
                        "The MySQL Host is <strong>never</strong> <code>localhost</code> on InfinityFree!<br>" .
                        "Go to your InfinityFree <strong>Control Panel (VistaPanel) &rarr; MySQL Databases</strong> and look for your <strong>MySQL Host Name</strong> (e.g. <code>sql123.infinityfree.com</code> or <code>sqlxxx.epizy.com</code>).<br><br>" .
                        "<strong>💻 If testing locally on XAMPP:</strong><br>" .
                        "1. Open the XAMPP Control Panel and click <strong>Start</strong> next to MySQL.<br>" .
                        "2. Use Host: <code>127.0.0.1</code>, Port: <code>3306</code>, Username: <code>root</code>, Password: (leave empty).</div>";
            } elseif (strpos($msg, '1045') !== false) {
                $hint = "<div style='margin-top:10px; padding:10px; background:rgba(0,0,0,0.04); border-radius:6px; font-size:13px; line-height:1.5;'>" .
                        "<strong>🔑 Access Denied (Bad Username or Password):</strong><br>" .
                        "• On InfinityFree: Username is like <code>epiz_12345678</code> or <code>if0_12345678</code>. Password is your vPanel hosting account password.<br>" .
                        "• On local XAMPP: Username is <code>root</code>, and password should be left blank.</div>";
            } elseif (strpos($msg, '1049') !== false) {
                $hint = "<div style='margin-top:10px; padding:10px; background:rgba(0,0,0,0.04); border-radius:6px; font-size:13px; line-height:1.5;'>" .
                        "<strong>📁 Unknown Database:</strong><br>" .
                        "You must create the database first before running the installer!<br>" .
                        "• On InfinityFree: Go to VistaPanel &rarr; <strong>MySQL Databases</strong> &rarr; enter database name (e.g. <code>mitid</code>) &rarr; click <strong>Create Database</strong>. Note the full name (e.g. <code>epiz_12345678_mitid</code>).<br>" .
                        "• On local XAMPP: Open <code>http://localhost/phpmyadmin</code> and click <strong>New</strong> &rarr; database name: <code>mitid</code>.</div>";
            }
            $error = "<strong>Database Error:</strong> " . htmlspecialchars($msg) . $hint;
        }
    }
}

